import '../scripts/browser-globals.js'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { empleadoInicialFichadas, claveEmpleadoFichadas } from '../src/views/fichadas.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => readFileSync(join(root, path), 'utf8')
const view = read('src/views/fichadas.js')
const calendar = read('src/components/jornadas-calendar-panel.js')
const empty = read('src/components/fichadas-empty-state.js')
const alertas = read('src/components/jornadas-alertas-panel.js')
const timeline = read('src/components/fichadas-timeline.js')
