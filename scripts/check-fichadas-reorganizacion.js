const cards = view.slice(view.indexOf('function createSummaryCards'), view.indexOf('export async function renderFichadas'))
const navegacion = view.slice(view.indexOf('onMovimientos:'), view.indexOf('function cargarAlertasPendientes'))

const ana = { id: 2, nombre: 'Ana', apellido: 'Gómez', activo: true }
const bruno = { id: 1, nombre: 'Bruno', apellido: 'Paz', activo: true }
const inactivo = { id: 3, nombre: 'Abel', apellido: 'Paz', activo: false }
assert.equal(empleadoInicialFichadas([bruno, ana, inactivo], { stored: null }), '2')
assert.equal(empleadoInicialFichadas([bruno, ana], { stored: '1' }), '1')
assert.equal(empleadoInicialFichadas([bruno, ana], { stored: '' }), '')
assert.equal(empleadoInicialFichadas([bruno, ana], { stored: '99' }), '2')
assert.equal(empleadoInicialFichadas([], { stored: null }), '')
assert.notEqual(claveEmpleadoFichadas(4), claveEmpleadoFichadas(9))
assert.equal(claveEmpleadoFichadas(4).includes('4'), true)
assert.equal(claveEmpleadoFichadas(null), '')

assert.equal(cards.includes('Posibles duplicados'), false)
assert.match(cards, /Movimientos totales/)
assert.match(cards, /label: 'Entradas'/)
assert.match(cards, /label: 'Salidas'/)
assert.match(cards, /createPendientesCard/)
